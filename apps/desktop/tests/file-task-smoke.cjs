const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const http = require('node:http');
const { _electron } = require('playwright');
const root = path.resolve(__dirname, '..');
const temporary = fs.mkdtempSync(path.join(os.tmpdir(), 'aegis-file-task-ui-'));
const folder = path.join(temporary, 'workspace'); fs.mkdirSync(folder);
const requests = [];
let app, server;
(async () => {
  server = http.createServer(async (req, res) => {
    let body = ''; for await (const chunk of req) body += chunk;
    requests.push(JSON.parse(body));
    res.writeHead(200, { 'Content-Type': 'application/json' });
    res.end(JSON.stringify({ choices: [{ message: { content: JSON.stringify({ content: '# Fixture report\n\n<script>window.badFile=true</script>\nUpdated by API' }) }, finish_reason: 'stop' }] }));
  });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  const env = { ...process.env }; delete env.ELECTRON_RUN_AS_NODE;
  const exe = process.env.BTK_DESKTOP_TEST_EXE;
  app = await _electron.launch({ executablePath: exe || path.join(root, 'node_modules/electron/dist/electron.exe'), args: [...(exe ? [] : [root]), `--user-data-dir=${path.join(temporary, 'profile')}`], env });
  const page = await app.firstWindow(); page.setDefaultTimeout(15000);
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  await app.evaluate(({ app, dialog }, folder) => {
    global.fileTaskConfirm = 1; global.fileTaskDialogs = []; global.fileTaskCodexCalls = 0;
    dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [folder] });
    dialog.showMessageBox = async (_window, options) => { global.fileTaskDialogs.push(options); return { response: global.fileTaskConfirm }; };
    const { CodexConnection } = process.mainModule.require(app.getAppPath() + '/electron/codex.cjs');
    CodexConnection.prototype.models = async () => [{ id: 'fixture-codex', name: 'Fixture' }];
    CodexConnection.prototype.complete = async () => { global.fileTaskCodexCalls++; return { status: 'completed', text: '{"content":"# Updated by login model"}' }; };
  }, folder);
  await page.waitForFunction(() => Boolean(window.btk));
  assert.equal(await page.evaluate(async () => { try { await window.btk.personal.fileTask.generate('default', 'notes.md', 'Denied'); return false; } catch { return true; } }), true);
  await page.evaluate(async port => {
    const p = window.btk.personal;
    await p.mode('personal');
    await p.save({ provider: 'local', endpoint: `http://127.0.0.1:${port}/v1`, model: 'file-fixture', maxTokens: 2048 });
    await p.folder();
  }, server.address().port);
  await page.reload();
  await page.getByRole('button', { name: '파일 작업', exact: true }).click();
  await page.getByLabel('파일 경로', { exact: true }).fill('notes.md');
  await page.getByLabel('작업 요청', { exact: true }).fill('Write a report');
  await app.evaluate(() => { global.fileTaskConfirm = 0; });
  await page.getByRole('button', { name: '수정안 생성', exact: true }).click();
  await page.getByRole('alert').filter({ hasText: '취소' }).waitFor();
  assert.equal(requests.length, 0);
  await app.evaluate(() => { global.fileTaskConfirm = 1; });
  await page.getByRole('button', { name: '수정안 생성', exact: true }).click();
  await page.getByRole('region', { name: '변경 비교', exact: true }).waitFor();
  assert.equal(fs.existsSync(path.join(folder, 'notes.md')), false);
  assert.equal(await page.evaluate(() => window.badFile), undefined);
  assert.equal(await page.locator('.file-task-review script').count(), 0);
  await app.evaluate(() => { global.fileTaskConfirm = 0; });
  await page.getByRole('button', { name: '검토 후 저장', exact: true }).click();
  await page.waitForFunction(() => !document.querySelector('.file-task-review button').disabled);
  assert.equal(fs.existsSync(path.join(folder, 'notes.md')), false);
  await app.evaluate(() => { global.fileTaskConfirm = 1; });
  await page.getByRole('button', { name: '검토 후 저장', exact: true }).click();
  await page.getByRole('status').filter({ hasText: '저장 완료' }).waitFor();
  assert.match(fs.readFileSync(path.join(folder, 'notes.md'), 'utf8'), /Updated by API/);
  await page.getByLabel('작업 요청', { exact: true }).fill('Revise again');
  fs.writeFileSync(path.join(folder, 'notes.md'), 'Original before request');
  await page.getByRole('button', { name: '수정안 생성', exact: true }).click();
  await page.getByRole('region', { name: '변경 비교', exact: true }).waitFor();
  assert.match(requests.at(-1).messages[0].content, /Original before request/);
  fs.writeFileSync(path.join(folder, 'notes.md'), 'External edit');
  await page.getByRole('button', { name: '검토 후 저장', exact: true }).click();
  await page.getByRole('alert').filter({ hasText: '외부에서 변경' }).waitFor();
  assert.equal(fs.readFileSync(path.join(folder, 'notes.md'), 'utf8'), 'External edit');
  await page.evaluate(async () => { await window.btk.personal.connection('codex'); await window.btk.personal.codex.model('fixture-codex'); });
  await page.reload();
  await page.getByRole('button', { name: '파일 작업', exact: true }).click();
  await page.getByLabel('파일 경로', { exact: true }).fill('notes.md');
  await page.getByLabel('작업 요청', { exact: true }).fill('Revise using the other model');
  await page.getByRole('button', { name: '수정안 생성', exact: true }).click();
  await page.getByRole('region', { name: '변경 비교', exact: true }).waitFor();
  assert.equal(await app.evaluate(() => global.fileTaskCodexCalls), 1);
  for (const width of [1440, 390]) {
    await page.setViewportSize({ width, height: 900 });
    await page.keyboard.press('Escape');
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    fs.mkdirSync(path.join(root, 'artifacts'), { recursive: true });
    await page.screenshot({ path: path.join(root, `artifacts/file-task-${width}.png`) });
  }
  await page.getByLabel('언어 / Language').selectOption('en');
  await page.getByRole('button', { name: 'Review and save', exact: true }).click();
  await page.getByRole('status').filter({ hasText: 'Saved' }).waitFor();
  assert.equal(fs.readFileSync(path.join(folder, 'notes.md'), 'utf8'), '# Updated by login model');
  const dialogs = await app.evaluate(() => global.fileTaskDialogs);
  assert.equal(dialogs.at(-1).title, 'Approve file save');
  assert.equal(dialogs.every(item => item.defaultId === 0 && item.cancelId === 0), true);
  assert.equal(await page.evaluate(async () => { try { await window.btk.personal.fileTask.generate('other-agent', 'notes.md', 'Denied'); return false; } catch { return true; } }), true);
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ status: 'passed', checks: ['native file generation', 'source reading', 'review before write', 'cancel transmission', 'cancel save', 'conflict protection', 'API and login adapters', 'English/Korean', 'desktop/mobile', 'agent and edition boundaries'], realProviderCalls: 0 }));
})().catch(error => { console.error(error); process.exitCode = 1; }).finally(async () => {
  await app?.close(); server?.closeAllConnections(); if (server) await new Promise(resolve => server.close(resolve));
  fs.rmSync(temporary, { recursive: true, force: true, maxRetries: 3 });
});
